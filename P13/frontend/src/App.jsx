import React, { useState, useEffect } from 'react';

const BACKEND_URL = 'http://localhost:5000';

export default function App() {
  const [tasks, setTasks] = useState([]);
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [loadingAI, setLoadingAI] = useState(false);
  const [aiNotice, setAiNotice] = useState('');
  const [error, setError] = useState('');

  const fetchTasks = async () => {
    try {
      const res = await fetch(`${BACKEND_URL}/tasks`);
      const data = await res.json();
      setTasks(data);
    } catch (e) {
      console.error(e);
    }
  };

  useEffect(() => {
    fetchTasks();
  }, []);

  const handleGenerateAIDescription = async () => {
    if (!title.trim()) {
      setError('Please provide a task title first!');
      return;
    }
    setError('');
    setLoadingAI(true);
    setAiNotice('');

    try {
      const res = await fetch(`${BACKEND_URL}/api/ai/generate-description`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ title })
      });
      const data = await res.json();

      if (data.description) {
        setDescription(data.description);
        if (data.fallback) {
          setAiNotice('Notice: Generated via resilient fallback template.');
        } else {
          setAiNotice('Success: Description generated via AI! You can edit it before saving.');
        }
      } else if (data.error) {
        setError(data.error);
      }
    } catch (err) {
      setError('Failed to reach backend AI endpoint.');
    } finally {
      setLoadingAI(false);
    }
  };

  const handleCreateTask = async (e) => {
    e.preventDefault();
    if (!title.trim()) return;

    try {
      const res = await fetch(`${BACKEND_URL}/tasks`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ title, description })
      });
      if (res.ok) {
        setTitle('');
        setDescription('');
        setAiNotice('');
        fetchTasks();
      }
    } catch (err) {
      setError('Error saving task.');
    }
  };

  return (
    <div style={{ maxWidth: '700px', margin: '40px auto', fontFamily: 'Arial, sans-serif', padding: '0 20px' }}>
      <h2>AI-Powered Task Management System</h2>
      <p style={{ color: '#555' }}>Practical 13: Responsible AI integration with server-side key security and fallback degradation.</p>

      {error && <div style={{ background: '#ffebee', color: '#c62828', padding: '10px', borderRadius: '4px', marginBottom: '15px' }}>{error}</div>}
      {aiNotice && <div style={{ background: '#e8f5e9', color: '#2e7d32', padding: '10px', borderRadius: '4px', marginBottom: '15px' }}>{aiNotice}</div>}

      <form onSubmit={handleCreateTask} style={{ background: '#f9f9f9', padding: '20px', borderRadius: '8px', border: '1px solid #ddd' }}>
        <div style={{ marginBottom: '15px' }}>
          <label style={{ display: 'block', fontWeight: 'bold', marginBottom: '5px' }}>Task Title:</label>
          <input 
            type="text" 
            placeholder="e.g. Implement Dockerized Deployment"
            value={title} 
            onChange={e => setTitle(e.target.value)}
            style={{ width: '100%', padding: '10px', boxSizing: 'border-box' }}
          />
        </div>

        <div style={{ marginBottom: '15px' }}>
          <button 
            type="button" 
            onClick={handleGenerateAIDescription}
            disabled={loadingAI}
            style={{ background: '#6200ea', color: '#fff', border: 'none', padding: '8px 16px', borderRadius: '4px', cursor: 'pointer' }}
          >
            {loadingAI ? 'Generating with AI...' : '? Auto-Generate Description (AI)'}
          </button>
        </div>

        <div style={{ marginBottom: '15px' }}>
          <label style={{ display: 'block', fontWeight: 'bold', marginBottom: '5px' }}>Description (Editable):</label>
          <textarea 
            rows="4" 
            placeholder="AI suggestions or custom description will appear here..." 
            value={description}
            onChange={e => setDescription(e.target.value)}
            style={{ width: '100%', padding: '10px', boxSizing: 'border-box' }}
          />
          <small style={{ color: '#777', display: 'block', marginTop: '4px' }}>
            Disclaimer: Content generated by AI is suggestive and should be reviewed by the user prior to final submission.
          </small>
        </div>

        <button 
          type="submit" 
          style={{ background: '#00c853', color: '#fff', border: 'none', padding: '10px 24px', fontWeight: 'bold', borderRadius: '4px', cursor: 'pointer' }}
        >
          Save Task
        </button>
      </form>

      <h3 style={{ marginTop: '40px' }}>Task List</h3>
      <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
        {tasks.length === 0 ? <p style={{ color: '#888' }}>No tasks created yet.</p> : (
          tasks.map(t => (
            <div key={t.id} style={{ background: '#fff', border: '1px solid #e0e0e0', padding: '15px', borderRadius: '6px' }}>
              <h4 style={{ margin: '0 0 8px 0' }}>{t.title}</h4>
              <p style={{ margin: '0 0 8px 0', color: '#444' }}>{t.description}</p>
              <small style={{ color: '#999' }}>Created: {new Date(t.createdAt).toLocaleString()}</small>
            </div>
          ))
        )}
      </div>
    </div>
  );
}
